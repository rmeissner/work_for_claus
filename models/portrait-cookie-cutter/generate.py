def contours(data: str) -> CrossSection:
    rings = [
        [tuple(map(float, point.split(","))) for point in ring.split()]
        for ring in data.strip().split("\n\n")
    ]
    return CrossSection(rings, FillRule.EvenOdd)


def parts():
    """Two individual solids, backs on Z=0, cutter first."""
    outline = contours(OUTLINE)
    details = contours(DETAILS)
    bounds = outline.bounds()
    factor = COOKIE_HEIGHT / (bounds[3] - bounds[1])
    outline = outline.scale((factor, factor))
    details = details.scale((factor, factor))
    flange = extrude(outline.offset(FLANGE) - outline, FLANGE_HEIGHT)
    # Start above the bed to avoid coplanar bottom faces in the flange union.
    wall_start = FLANGE_HEIGHT - 0.2
    wall = extrude(outline.offset(WALL) - outline, BLADE_START - wall_start).translate(
        (0, 0, wall_start)
    )
    blade = extrude(outline.offset(BLADE) - outline, CUTTER_HEIGHT - BLADE_START)
    cutter = flange + wall + blade.translate((0, 0, BLADE_START))
    base = outline.offset(-STAMP_CLEARANCE)
    stamp = extrude(base, STAMP_BASE) + extrude(
        details ^ base, RELIEF_HEIGHT + 0.2
    ).translate((0, 0, STAMP_BASE - 0.2))
    return cutter, stamp


def main() -> None:
    cutter, stamp = parts()
    plate = layout_on_plate([cutter, stamp], PLATE_GAP)
    for solid, filename in (
        (plate, "portrait-cookie-cutter"),
        (cutter, "part-cutter"),
        (stamp, "part-stamp"),
    ):
        assert_printable(solid)
        if filename != "portrait-cookie-cutter" and len(solid.decompose()) != 1:
            raise ValueError(f"{filename} must be one connected solid")
        path = Path(__file__).with_name(filename + ".stl")
        write_stl(solid, path, filename)
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
